#!/usr/bin/env python3
"""The mod-owned asset adapter of the Master System asset-replacement example (SEG-147-T007, ADR 0324). It turns the mod's text assets (declared in mod.toml as `asset` sources of class `data`) into a
typed `rom-edit-set` for THIS synthetic cartridge format (rom_format.json). It is not a universal decoder: a real mod writes its own adapter for the data formats it has understood.

Everything is checked before anything is written: the original image is the declared revision (SHA-256), every region the adapter replaces still holds the original bytes rom_format.json pins
(SHA-256), and every asset fits its region and value ranges. Each edit carries the original bytes as its expected value, so `segarecomp mod apply` asserts them again.

usage: encode_assets.py <original.sms> [--project <dir>] [--check]     --check: fail unless edits/main.edits is exactly what the assets produce"""
import hashlib
import json
import pathlib
import re
import sys
import tomllib

HERE = pathlib.Path(__file__).resolve().parent


class AssetError(Exception):
    pass


def lines_of(text):
    return [line.rstrip() for line in text.splitlines() if line.strip() and not line.startswith("#")]


def encode_palette(text, region):
    """`<index> <red> <green> <blue>`, levels 0..3 -> one --BBGGRR byte at the index."""
    out = {}
    for line in lines_of(text):
        if not re.fullmatch(r"\d{1,2}( [0-3]){3}", line):
            raise AssetError(f"palette: a line is `<index> <r> <g> <b>` with levels 0..3: {line!r}")
        index, red, green, blue = map(int, line.split())
        if index >= region["entries"] or index in out:
            raise AssetError(f"palette: index {index} is out of range or repeated")
        out[index] = bytes([red | green << 2 | blue << 4])
    return out


def encode_tiles(text, region):
    """`tile <number>` followed by 8 rows of 8 hexadecimal colour indices -> the 32-byte 4bpp planar pattern."""
    blocks = []   # (tile number, rows)
    for line in lines_of(text):
        if line.startswith("tile "):
            name = line[5:]
            if not name.isdigit() or int(name) >= region["entries"] or any(int(name) == number for number, _ in blocks):
                raise AssetError(f"tiles: tile number {name!r} is out of range or repeated")
            blocks.append((int(name), []))
        elif not blocks or not re.fullmatch(r"[0-9a-f]{8}", line):
            raise AssetError(f"tiles: a row is 8 lower-case hexadecimal digits after a `tile` line: {line!r}")
        else:
            blocks[-1][1].append([int(c, 16) for c in line])
    out = {}
    for number, rows in blocks:
        if len(rows) != 8:
            raise AssetError(f"tiles: tile {number} has {len(rows)} rows, not 8")
        out[number] = bytes(sum(((rows[y][x] >> plane) & 1) << (7 - x) for x in range(8)) for y in range(8) for plane in range(4))
    return out


def encode_room(text, region, tile_count):
    """4 rows of 8 tile numbers (the game's room table)."""
    rows = [line.split() for line in lines_of(text)]
    if len(rows) != region["rows"] or any(len(r) != region["columns"] for r in rows):
        raise AssetError(f"room: the table is {region['rows']} rows of {region['columns']} tile numbers")
    values = [v for r in rows for v in r]
    if not all(v.isdigit() and int(v) < tile_count for v in values):
        raise AssetError(f"room: a tile number is 0..{tile_count - 1}")
    return {0: bytes(map(int, values))}


def encode_text(text, region, charset):
    """One line in the cartridge's own character set, padded with spaces to the fixed length."""
    lines = lines_of(text)
    if len(lines) != 1 or len(lines[0]) > region["length"] or any(c not in charset for c in lines[0]):
        raise AssetError(f"text: one line of at most {region['length']} characters from {charset!r}")
    return {0: bytes(charset.index(c) for c in lines[0].ljust(region["length"]))}


def edits_for(project, rom):
    fmt = json.loads((HERE / "rom_format.json").read_text(encoding="utf-8"))
    mod = tomllib.loads((project / "mod.toml").read_text(encoding="utf-8"))
    digest = hashlib.sha256(rom).hexdigest()
    revision = next((r["label"] for r in mod["target"]["revision"] if r["sha256"] == digest), None)
    if revision is None:
        raise AssetError("the image is not a revision this mod declares")
    declared = {s["format"]: s["path"] for s in mod["source"] if s["kind"] == "asset" and s.get("asset_class") == "data"}
    unknown = sorted(set(declared) - {r["format"] for r in fmt["regions"]})
    if unknown:
        raise AssetError(f"no encoder for the declared asset format(s) {unknown}")
    tile_count = next(r["entries"] for r in fmt["regions"] if r["format"] == "demo-tiles")
    out = ["# Generated by encode_assets.py from the mod's assets; do not edit by hand."]
    for region in fmt["regions"]:
        if region["format"] not in declared:
            continue
        start, size = int(region["offset"], 16), region["size"]
        original = rom[start:start + size]
        if len(original) != size or hashlib.sha256(original).hexdigest() != region["original_sha256"]:
            raise AssetError(f"{region['name']}: the original bytes of the region are not the ones this adapter understands")
        text = (project / declared[region["format"]]).read_text(encoding="ascii")
        kind = region["format"]
        if kind == "demo-palette":
            items, stride = encode_palette(text, region), 1
        elif kind == "demo-tiles":
            items, stride = encode_tiles(text, region), 32
        elif kind == "demo-room":
            items, stride = encode_room(text, region, tile_count), size
        else:
            items, stride = encode_text(text, region, fmt["charset"]), size
        for index, value in sorted(items.items()):
            at = index * stride
            if at + len(value) > size:
                raise AssetError(f"{region['name']}: the encoded asset does not fit its region")
            before = original[at:at + len(value)]
            if value != before:
                out.append(f"{revision} bytes 0x{start + at:08x} {before.hex()} {value.hex()}")
    return "\n".join(out) + "\n"


def main(argv):
    check = "--check" in argv
    argv = [a for a in argv if a != "--check"]
    project = HERE
    if "--project" in argv:
        at = argv.index("--project")
        project = pathlib.Path(argv[at + 1])
        del argv[at:at + 2]
    if len(argv) != 1:
        sys.exit(__doc__)
    try:
        text = edits_for(project, pathlib.Path(argv[0]).read_bytes())
    except (AssetError, OSError, UnicodeError) as error:
        print(f"encode_assets: {error}", file=sys.stderr)
        return 1
    target = project / "edits" / "main.edits"
    if check:
        if target.read_text(encoding="ascii") != text:
            print("encode_assets: edits/main.edits is stale", file=sys.stderr)
            return 1
        return 0
    target.parent.mkdir(exist_ok=True)
    target.write_bytes(text.encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
