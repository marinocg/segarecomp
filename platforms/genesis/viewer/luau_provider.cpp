// SEG-137-T007 (ADR 0296): the live Luau seam of a generated-native Genesis program. The build (`segarecomp build --luau-package`) verified a Luau-only package, compiled its scripts with the pinned trusted
// compiler and linked the result into THIS program as a constant (luau_artifact.c); this file runs it. It is exactly the fixed HUD overlay path of ADR 0267: the viewer already asks any linked
// `segarecomp_patch_provider` for a frame and, when the provider accepts the HUD component, draws the RGBA overlay it returns. Nothing else is read or written: no guest memory, no input, no
// scenery, no frame data (the API's frame/work-RAM values are not published here: the build refuses a package that requires them). It is not a scheduler: one `render(frame)` call per presented
// frame, `reset()` once before the first.
//
// Failure isolation: a script fault (error, budget, memory, capability, range, ...) disables the mod for the rest of the session; the frame is then presented without overlay, the game goes on, and
// one `LUAU_MOD_FAULT` line names the cause. A VM that cannot be created or an artifact that does not verify declines every frame the same way. Nothing here ever stops the guest.
#include "segarecomp/luau_api.hpp"

#include "segarecomp_genesis_patch.h"

#include <algorithm>
#include <cstdio>
#include <cstring>
#include <memory>
#include <string>
#include <utility>
#include <vector>

extern "C" {
extern const unsigned char segarecomp_luau_artifact[];   // the stored compiled form (luau_stored.cpp), generated by the build
extern const unsigned long segarecomp_luau_artifact_size;
extern const char segarecomp_luau_identity[];            // package identity (64 hex)
extern const char segarecomp_luau_bytecode_digest[];     // the digest recorded when the build verified the artifact
extern const char segarecomp_luau_capabilities[];        // comma separated catalogue names the build granted
extern const unsigned long segarecomp_luau_memory_bytes, segarecomp_luau_budget_units;   // the package's own (lower) limits, 0 = policy
extern const char segarecomp_luau_mod_id[];
}

namespace {

using namespace segarecomp;

struct State {
  std::unique_ptr<luau::Vm> vm;
  bool started = false, failed = false;
  std::uint64_t frame = 0;
  luau::OverlayImage image;
  bool fixed = false;   // some request drew into the fixed HUD overlay (layer 0)
  std::vector<std::pair<luau::OverlayLayerDecl, luau::OverlayImage>> layers;   // SEG-140-T004: positioned layers of the frame (declaration order)
  bool have_image = false;
};

State g_state;

// Script text is printable ASCII (the VM guarantees it) but may contain a quotation mark or a backslash: escape both so the line stays valid JSON.
std::string json_escaped(const std::string &text) {
  std::string out;
  for (const char c : text) {
    if (c == '"' || c == '\\') out += '\\';
    out += c;
  }
  return out;
}

void report_fault(const char *callback, const luau::CallResult &r, std::uint64_t frame) {
  std::fprintf(stderr, "LUAU_MOD_FAULT {\"cause\":\"%s\",\"mod\":\"%s\",\"callback\":\"%s\",\"frame\":%llu,\"message\":\"", luau::fault_name(r.fault), segarecomp_luau_mod_id, callback,
               static_cast<unsigned long long>(frame));
  for (const char c : r.message) std::fputc(c == '"' || c == '\\' || static_cast<unsigned char>(c) < 0x20 || static_cast<unsigned char>(c) > 0x7E ? '?' : c, stderr);
  std::fputs("\"}\n", stderr);
}

bool start(State &s) {
  s.started = true;
  const std::span<const std::uint8_t> stored(segarecomp_luau_artifact, static_cast<std::size_t>(segarecomp_luau_artifact_size));
  const luau::CompileResult loaded = luau::load_stored(segarecomp_luau_identity, stored, segarecomp_luau_bytecode_digest);
  if (!loaded.ok) {
    std::fprintf(stderr, "LUAU_MOD_REFUSED {\"class\":\"%s\"}\n", loaded.rejection.code.c_str());
    return false;
  }
  luau::HostConfig host;
  for (const char *p = segarecomp_luau_capabilities; *p != '\0';) {
    const char *end = std::strchr(p, ',');
    const std::string name = end != nullptr ? std::string(p, end) : std::string(p);
    if (!name.empty()) host.capabilities.push_back(name);
    if (end == nullptr) break;
    p = end + 1;
  }
  luau::Limits limits = luau::policy_limits();
  if (segarecomp_luau_memory_bytes != 0 && segarecomp_luau_memory_bytes < limits.memory_bytes) limits.memory_bytes = segarecomp_luau_memory_bytes;
  if (segarecomp_luau_budget_units != 0 && segarecomp_luau_budget_units < limits.callback_units) limits.callback_units = segarecomp_luau_budget_units;
  s.vm = luau::Vm::create(segarecomp_luau_identity, limits, host);
  if (!s.vm) {
    std::fputs("LUAU_MOD_REFUSED {\"class\":\"E_VM_CREATE\"}\n", stderr);
    return false;
  }
  const luau::CallResult load = s.vm->load(loaded.compiled);
  if (!load.ok) {
    report_fault("load", load, 0);
    return false;
  }
  std::fprintf(stderr, "LUAU_MOD_LOADED {\"mod\":\"%s\",\"package_identity\":\"%s\",\"bytecode_digest\":\"%s\",\"capabilities\":\"%s\"}\n", segarecomp_luau_mod_id, segarecomp_luau_identity,
               segarecomp_luau_bytecode_digest, segarecomp_luau_capabilities);
  luau::Output out;
  const luau::CallResult reset = s.vm->run_callback("reset", luau::FrameInput{}, 0, out);
  if (!reset.ok) {
    report_fault("reset", reset, 0);
    return false;
  }
  for (const std::string &line : out.log) std::fprintf(stderr, "LUAU_MOD_LOG {\"line\":\"%s\"}\n", json_escaped(line).c_str());
  return true;
}

void prepare(void *state, const GenesisCompatFrame *frame, GenesisCompatDecision *out) {
  State &s = *static_cast<State *>(state);
  out->accepted = 0;
  out->reason = GENESIS_COMPAT_OK;
  s.have_image = false;
  if ((frame->requested & GENESIS_COMPAT_HUD) == 0 || s.failed) {
    if (s.failed) out->reason = GENESIS_COMPAT_FAULT;
    return;
  }
  if (!s.started && !start(s)) s.failed = true;
  if (s.failed) {
    out->reason = GENESIS_COMPAT_FAULT;
    return;
  }
  luau::FrameInput in;
  in.number = s.frame++;
  luau::Output result;
  const luau::CallResult r = s.vm->run_callback("render", in, 1, result);
  if (!r.ok) {
    report_fault("render", r, in.number);
    s.failed = true;   // the mod is disabled for the rest of the session; the game carries on
    out->reason = GENESIS_COMPAT_FAULT;
    return;
  }
  for (const std::string &line : result.log) std::fprintf(stderr, "LUAU_MOD_LOG {\"line\":\"%s\"}\n", json_escaped(line).c_str());
  if (result.overlay.empty()) return;
  s.image = luau::rasterize_overlay(result.overlay);
  s.fixed = std::any_of(result.overlay.begin(), result.overlay.end(), [](const luau::OverlayOp &op) { return op.layer == 0; });
  s.layers.clear();
  for (const luau::OverlayLayerDecl &d : result.layers) s.layers.emplace_back(d, luau::rasterize_layer(d, result.overlay));
  s.have_image = true;
  out->accepted = GENESIS_COMPAT_HUD;
  if (!result.scene.empty() && result.scene.size() <= GENESIS_COMPAT_SCENE_MAX) std::memcpy(out->scene, result.scene.c_str(), result.scene.size() + 1U);   // SEG-139-T004: the mod's own scene claim (validated token)
}

int scenery_word(void *, unsigned, unsigned, int, int, int, uint16_t *) { return 0; }

int hud(void *state, GenesisCompatOverlay *out) {
  State &s = *static_cast<State *>(state);
  if (!s.have_image || out->capacity < s.image.rgba.size()) return 0;
  const bool fixed = s.fixed;   // only a request that drew into the fixed overlay makes the legacy path show anything
  if (fixed) {
    std::memcpy(out->rgba, s.image.rgba.data(), s.image.rgba.size());
    out->width = static_cast<std::uint16_t>(s.image.width);
    out->height = static_cast<std::uint16_t>(s.image.height);
  }
  out->fallback_x = 0;
  out->fallback_y = 0;
  if (out->layer_rgba != nullptr) {   // SEG-140-T004: the declared layers, packed one after another into the host's buffer
    std::size_t offset = 0;
    out->layer_count = 0;
    for (const auto &entry : s.layers) {
      const std::size_t bytes = entry.second.rgba.size();
      if (out->layer_count >= GENESIS_COMPAT_LAYERS_MAX || offset + bytes > out->layer_capacity) break;
      std::memcpy(out->layer_rgba + offset, entry.second.rgba.data(), bytes);
      GenesisCompatLayer &l = out->layers[out->layer_count++];
      std::memset(&l, 0, sizeof l);
      l.width = static_cast<std::uint16_t>(entry.first.w);
      l.height = static_cast<std::uint16_t>(entry.first.h);
      l.anchor = static_cast<std::uint8_t>(entry.first.anchor);
      l.reference = static_cast<std::uint8_t>(entry.first.reference);
      l.z = static_cast<std::uint8_t>(entry.first.z);
      l.dx = static_cast<std::int16_t>(entry.first.dx);
      l.dy = static_cast<std::int16_t>(entry.first.dy);
      l.offset = static_cast<std::uint32_t>(offset);
      offset += bytes;
    }
  }
  return fixed || out->layer_count > 0 ? 1 : 0;
}

const GenesisNativeCompat kTable = {GENESIS_NATIVE_COMPAT_ABI, "luau-hud-host", 1, GENESIS_COMPAT_HUD, prepare, scenery_word, hud};

}  // namespace

extern "C" const GenesisNativeCompat *segarecomp_patch_provider(void **state_out) {
  *state_out = &g_state;
  return &kTable;
}
