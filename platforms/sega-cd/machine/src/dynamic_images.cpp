std::string dynamic_images_identity(const std::vector<DynamicImageSpec> &images, std::string_view policy) {
  std::ostringstream id;
  id << "dynamic.v1 " << policy << "\n";
  for (const auto &image : images) {
    const std::string mask = image.candidate.empty() ? std::string("all") : sha256_hex(image.candidate);
    id << image.track_offset << " " << sha256_hex(image.bytes) << " " << mask << "\n";
  }
  const std::string text = id.str();
  return sha256_hex(std::span<const std::uint8_t>(reinterpret_cast<const std::uint8_t *>(text.data()), text.size()));
}

DynamicEmission emit_dynamic_images(const DiscImage &disc, const std::vector<DynamicImageSpec> &images, std::string_view policy,
                                    bool verify_only_guard, unsigned jobs) {
  DynamicEmission out;
  const auto fail = [&](DynamicError e, std::size_t index) {
    out.error = e;
    out.error_index = static_cast<std::uint32_t>(index);
    return out;
  };
  if (images.empty()) return out;
  if (images.size() > kDynamicMaxImages) return fail(DynamicError::too_many_images, images.size());
  if (disc.tracks().empty() || disc.tracks().front().type == DiscTrackType::audio) return fail(DynamicError::image_invalid, 0);
  const auto &track = disc.tracks().front();
  std::set<std::string> seen;
  std::uint64_t requested = 0;
  // ---- validation against the verified disc: an image is exactly what the disc holds at its extent ----
  std::vector<std::string> digests(images.size());
  for (std::size_t i = 0; i < images.size(); ++i) {
    const auto &image = images[i];
    const std::uint64_t blocks = (image.bytes.size() + kDiscUserBytes - 1U) / kDiscUserBytes;
    if (image.bytes.empty() || image.bytes.size() > kDynamicMaxImageBytes || image.track_offset % kDiscUserBytes != 0U ||
        image.track_offset / kDiscUserBytes + blocks > track.sector_count)
      return fail(DynamicError::image_invalid, i);
    if (!image.candidate.empty() && image.candidate.size() != image.bytes.size() / 2U) return fail(DynamicError::candidate_size, i);
    std::vector<std::uint8_t> disc_bytes;
    std::array<std::uint8_t, kDiscUserBytes> block{};
    for (std::uint64_t k = 0; k < blocks; ++k) {
      if (disc.read_user_data(track.first_lba + image.track_offset / kDiscUserBytes + static_cast<std::uint32_t>(k), block) != DiscError::none)
        return fail(DynamicError::image_invalid, i);
      disc_bytes.insert(disc_bytes.end(), block.begin(), block.end());
    }
    disc_bytes.resize(image.bytes.size());
    if (disc_bytes != image.bytes) return fail(DynamicError::digest_mismatch, i);
    digests[i] = sha256_hex(image.bytes);
    if (!seen.insert(digests[i]).second) return fail(DynamicError::duplicate_content, i);
    requested += image.candidate.empty() ? image.bytes.size() / 2U : static_cast<std::uint64_t>(std::count(image.candidate.begin(), image.candidate.end(), std::uint8_t{1}));
    if (requested > kDynamicMaxCandidateOffsets) return fail(DynamicError::too_many_candidates, i);
  }
  // ---- phase 1: the instruction bytes at every candidate offset (one decode each; no lowering) ----
  std::vector<std::vector<Raw>> raws(images.size());
  std::vector<DynamicImageStats> stats(images.size());
  parallel_for(images.size(), jobs, [&](std::size_t i) {
    const auto &image = images[i];
    const auto length = static_cast<std::uint32_t>(image.bytes.size());
    const std::uint32_t n = length / 2U;
    raws[i].assign(n, Raw{});
    auto &st = stats[i];
    st.id = static_cast<std::uint32_t>(i + 1U);
    st.track_offset = image.track_offset;
    st.length = length;
    st.sha256 = digests[i];
    const std::span<const std::uint8_t> window(image.bytes.data(), static_cast<std::size_t>(n) * 2U);
    for (std::uint32_t k = 0; k < n; ++k) {
      if (!image.candidate.empty() && image.candidate[k] == 0U) continue;
      ++st.candidate_offsets;
      const std::uint32_t offset = k * 2U;
      const DecodeSource source{CpuVariant::mc68000, M68kProgramAddress{TargetAddressSpace::m68k_program, 0x00200000U + offset}, MoveqImageOffset{offset}};
      const auto result = decode_m68k_instruction(window, source, M68kDecodeProfile::general_startup);
      const auto *decoded = std::get_if<M68kDecodedInstruction>(&result);
      if (decoded == nullptr || decoded->raw_bytes.empty() || decoded->raw_bytes.size() > 10U) {
        ++st.not_decoded;
        continue;
      }
      Raw r;
      r.n = static_cast<std::uint8_t>(decoded->raw_bytes.size());
      std::memcpy(r.b.data(), decoded->raw_bytes.data(), r.n);
      raws[i][k] = r;
    }
  });
  // ---- the distinct encodings, in a deterministic order ----
  std::vector<Raw> unique;
  for (const auto &list : raws)
    for (const auto &r : list)
      if (r.n != 0U) unique.push_back(r);
  std::sort(unique.begin(), unique.end());
  unique.erase(std::unique(unique.begin(), unique.end()), unique.end());
  out.unique_encodings = unique.size();
  // ---- phase 2: derive the body of each distinct encoding (the CPU-owned lowering at three sentinels), one slice per unit ----
  const std::size_t slices = (unique.size() + kDynamicBodySliceSize - 1U) / kDynamicBodySliceSize;
  std::vector<std::vector<std::uint8_t>> ok(slices);                 // per slice, per body: 1 when a body was derived
  std::vector<DynamicUnit> body_units(slices);
  std::vector<std::uint8_t> body_length(unique.size(), 0U);   // per distinct encoding: its length when a body was derived
  std::vector<std::map<std::string, std::uint64_t>> reasons(slices);
  std::vector<std::uint64_t> text_bytes(slices, 0U);
  parallel_for(slices, jobs, [&](std::size_t s) {
    const std::size_t first = s * kDynamicBodySliceSize, last = std::min(unique.size(), first + kDynamicBodySliceSize);
    std::ostringstream text;
    text << prologue();
    std::ostringstream table;
    table << "const ScdDispatchFunction scd_dyn_slice" << s << "[" << kDynamicBodySliceSize << "] = {";
    ok[s].assign(kDynamicBodySliceSize, 0U);
    std::uint32_t functions = 0;
    for (std::size_t r = first; r < first + kDynamicBodySliceSize; ++r) {
      if (r < last) {
        const Raw &raw = unique[r];
        const std::span<const std::uint8_t> bytes(raw.b.data(), raw.n);
        const DynamicBody body = derive_dynamic_body(bytes, raw.n, 0U);
        if (body.status == DynamicBodyStatus::ok) {
          text << function_text(r + 1U, body, verify_only_guard);
          ok[s][r - first] = 1U;
          body_length[r] = raw.n;
          ++functions;
          table << (r == first ? "" : ", ") << body_name(r + 1U);
          continue;
        }
        ++reasons[s][body.status == DynamicBodyStatus::source_relative_refused
                         ? std::string("source_relative_refused:") + source_relative_status_name(body.derive)
                         : std::string(dynamic_body_status_name(body.status))];
      }
      table << (r == first ? "" : ", ") << "NULL";
    }
    table << "};\n";
    text << table.str();
    body_units[s].name = "d_b" + hex(static_cast<std::uint32_t>(s), 5) + ".c";
    body_units[s].c_source = text.str();
    body_units[s].functions = functions;
    text_bytes[s] = body_units[s].c_source.size();
  });
  std::map<std::string, std::uint64_t> reason_total;
  for (std::size_t s = 0; s < slices; ++s) {
    out.bodies += body_units[s].functions;
    out.body_text_bytes += text_bytes[s];
    for (const auto &[reason, count] : reasons[s]) reason_total[reason] += count;
    out.units.push_back(std::move(body_units[s]));
  }
  out.refused = out.unique_encodings - out.bodies;
  for (const auto &[reason, count] : reason_total) out.refused_reasons.emplace_back(reason, count);
  out.body_units = static_cast<std::uint32_t>(slices);
  // ---- phase 3: one map per image: which body serves which source offset ----
  std::vector<DynamicUnit> map_units(images.size());
  std::vector<std::uint8_t> keep(images.size(), 0U);
  parallel_for(images.size(), jobs, [&](std::size_t i) {
    const auto &list = raws[i];
    std::ostringstream text;
    text << prologue() << "const uint32_t scd_dyn_map" << (i + 1U) << "[" << std::max<std::size_t>(list.size(), 1U) << "] = {";
    std::uint64_t compiled = 0;
    for (std::size_t k = 0; k < list.size(); ++k) {
      std::uint64_t value = 0;
      if (list[k].n != 0U) {
        const auto it = std::lower_bound(unique.begin(), unique.end(), list[k]);
        const std::uint64_t rank = static_cast<std::uint64_t>(it - unique.begin());
        if (ok[rank / kDynamicBodySliceSize][rank % kDynamicBodySliceSize] != 0U) {
          value = rank + 1U;
          ++compiled;
        }
      }
      if (k % 32U == 0U) text << "\n";
      text << value << ",";
    }
    if (list.empty()) text << "0";
    text << "};\n";
    stats[i].compiled_offsets = compiled;
    stats[i].refused = stats[i].candidate_offsets - stats[i].not_decoded - compiled;
    keep[i] = compiled != 0U ? 1U : 0U;
    map_units[i].name = "d_m" + hex(static_cast<std::uint32_t>(i + 1U), 4) + ".c";
    map_units[i].c_source = text.str();
  });
  // An image with no compiled offset is reported but not shipped: nothing could ever run through it.
  std::vector<std::size_t> shipped;
  for (std::size_t i = 0; i < images.size(); ++i) {
    out.candidate_offsets += stats[i].candidate_offsets;
    out.compiled_offsets += stats[i].compiled_offsets;
    if (keep[i] != 0U) {
      shipped.push_back(i);
      out.map_text_bytes += map_units[i].c_source.size();
      out.units.push_back(std::move(map_units[i]));
    }
  }
  out.images = stats;
  // ---- the program unit's declarations ----
  std::ostringstream decl;
  for (std::size_t s = 0; s < slices; ++s) decl << "extern const ScdDispatchFunction scd_dyn_slice" << s << "[" << kDynamicBodySliceSize << "];\n";
  for (const std::size_t i : shipped) decl << "extern const uint32_t scd_dyn_map" << (i + 1U) << "[];\n";
  decl << "static const ScdDispatchFunction *const scd_dyn_slice_table[] = {";
  for (std::size_t s = 0; s < slices; ++s) decl << (s ? ", " : "") << "scd_dyn_slice" << s;
  if (slices == 0U) decl << "NULL";
  decl << "};\nstatic const uint8_t scd_dyn_lengths[] = {";
  for (std::size_t r = 0; r < body_length.size(); ++r) decl << (r % 64U == 0U ? "\n" : "") << static_cast<unsigned>(body_length[r]) << ",";
  if (body_length.empty()) decl << "0";
  decl << "};\nstatic const ScdDynamicImage scd_dyn_images[] = {\n";
  for (const std::size_t i : shipped) {
    const auto &st = stats[i];
    decl << "  {" << st.id << "U, " << track.first_lba + st.track_offset / kDiscUserBytes << "U, " << st.length << "U, \"" << st.sha256 << "\", scd_dyn_map" << st.id << "},\n";
  }
  if (shipped.empty()) decl << "  {0U, 0U, 0U, \"\", NULL}\n";
  std::uint64_t shipped_bytes = 0;
  for (const std::size_t i : shipped) shipped_bytes += stats[i].length;
  decl << "};\nstatic const ScdDynamicProgram scd_dynamic_program = {scd_dyn_images, " << shipped.size() << "U, scd_dyn_slice_table, " << kDynamicBodySliceSize << "U, "
       << unique.size() << "U, scd_dyn_lengths, " << shipped_bytes << "U, " << out.compiled_offsets << "U, " << out.bodies << "U, \"" << policy << "\"};\n";
  out.program_text = decl.str();
  out.identity = dynamic_images_identity(images, policy);
  return out;
}

