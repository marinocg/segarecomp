#!/usr/bin/env python3
"""SEG-050 (ADR 0110/0111): attributable generated-C size and compile CPU of an M68K emission (measurement only).

Emits the Genesis M68K generated C with the unchanged `emit-general-startup-bridge-c --reset-entry --immutable-rom-aot` route (optionally with ADR 0049
alias descriptors, RAM thunks and an admission option) and compiles every emitted translation unit with the project warning set at -O1, reporting
aggregates only: identities (from the enumeration line), generated bytes, units, compile CPU/wall and the admission report class. Descriptors are given
on the command line from private local inputs and are never printed. Used to attribute cost to materialized images by differencing two emissions.

usage: seg050_materialized_cost.py --segarecomp <cli> --rom <image> --runtime-dir <platforms/genesis> --work <ignored-dir>
           [--alias E:S:L]... [--emit-arg X]... [--cc gcc] [--jobs N] [--no-compile]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import resource
import shutil
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--segarecomp", required=True)
    ap.add_argument("--rom", required=True)
    ap.add_argument("--runtime-dir", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--alias", action="append", default=[])
    ap.add_argument("--emit-arg", action="append", default=[])
    ap.add_argument("--cc", default="gcc")
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--no-compile", action="store_true")
    args = ap.parse_args()
    rom = pathlib.Path(args.rom).resolve()
    work = pathlib.Path(args.work).resolve()
    shutil.rmtree(work, ignore_errors=True)
    shards = work / "generated"
    shards.mkdir(parents=True)
    sha = hashlib.sha256(rom.read_bytes()).hexdigest()
    cmd = [args.segarecomp, "emit-general-startup-bridge-c", "--rom", str(rom), "--reset-entry", "--rom-sha256", sha, "--immutable-rom-aot"]
    for alias in args.alias:
        e, s, n = alias.split(":")
        cmd += ["--immutable-copy-alias", "%08x:%08x:%08x" % (int(e, 16), int(s, 16), int(n, 16))]
    cmd += args.emit_arg + ["--generated-c-output", str(work / "bridge.c"), "--generated-c-shard-dir", str(shards)]
    started = time.time()
    done = subprocess.run(cmd, capture_output=True, text=True, timeout=3600)
    if done.returncode != 0:
        print(json.dumps({"emit": "failed", "rc": done.returncode}))
        return 1
    record = {"emit_seconds": round(time.time() - started, 1)}
    match = re.search(r"accepted_count=(\d+)", done.stderr)
    record["identities"] = int(match.group(1)) if match else None
    admission = re.search(r"m68k admission: requested=optimized (.*)", done.stderr)
    if admission:
        fields = dict(t.split("=", 1) for t in admission.group(1).split() if "=" in t)
        record["admission"] = {k: fields[k] for k in ("producer", "fallback", "reason", "detail", "universe", "k0", "k", "pruned", "validator") if k in fields}
    manifest = shards / "bridge_generated.units"
    units = [shards / line for line in manifest.read_text().split() if line] if manifest.exists() else [work / "bridge.c"]
    record["units"] = len(units)
    record["generated_c_bytes"] = sum(p.stat().st_size for p in shards.rglob("*") if p.is_file())
    if not args.no_compile:
        root = pathlib.Path(args.runtime_dir).resolve().parents[1]
        includes = [root / "platforms/genesis/runtime", root / "libs/codegen/c11/include", root / "libs/device/sega/psg/include", root / "libs/device/sega/ym2612/include", shards]
        flags = ["-std=c11", "-Wall", "-Wextra", "-pedantic", "-O1", "-Wno-misleading-indentation"] + sum([["-I", str(i)] for i in includes], [])
        before = resource.getrusage(resource.RUSAGE_CHILDREN)
        wall = time.time()
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            codes = list(pool.map(lambda u: subprocess.run([args.cc] + flags + ["-c", "-o", "/dev/null", str(u)], capture_output=True).returncode, units))
        after = resource.getrusage(resource.RUSAGE_CHILDREN)
        record["compile_ok"] = all(c == 0 for c in codes)
        record["compile_wall_seconds"] = round(time.time() - wall, 1)
        record["compile_cpu_seconds"] = round((after.ru_utime - before.ru_utime) + (after.ru_stime - before.ru_stime), 1)
    shutil.rmtree(shards, ignore_errors=True)
    print(json.dumps(record, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
