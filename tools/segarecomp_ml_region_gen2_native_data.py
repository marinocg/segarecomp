#!/usr/bin/env python3
"""SEG-049-T003 (ADR 0102): deterministic generator of the checked-in NATIVE gen2 M3 weight table from the frozen research artifacts.

The product build never runs this (the generated `.inc` is checked in); `--check` is the drift test used by CI/tests. Pure Python stdlib.
Every constant embedded natively (model digest, representation / token-schema / rank-plan digests, policy, weight-table digest) is read
from the frozen artifacts and cross-checked against them here, so the native identity cannot silently diverge from the research freeze.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools"
MODEL = TOOLS / "segarecomp_ml_region_gen2.model.json"
FROZEN = TOOLS / "segarecomp_ml_region_gen2.frozen.json"
OUTPUT = ROOT / "platforms" / "genesis" / "machine" / "src" / "ml_region_gen2_model_data.inc"

# (state-dict name, shape) of the frozen M3 architecture, in the order the native evaluator consumes them.
SHAPES = {
    "emb_hi.weight": (256, 8), "emb_lo.weight": (256, 8),
    "tok.0.weight": (3, 2), "tok.1.weight": (6, 2), "tok.2.weight": (8, 3), "tok.3.weight": (8, 3),
    "tok.4.weight": (13, 3), "tok.5.weight": (13, 3), "tok.6.weight": (4, 2), "tok.7.weight": (4, 2),
    "stem.weight": (48, 36, 5), "stem.bias": (48,), "bn1.weight": (48,), "bn1.bias": (48,), "bn1.running_mean": (48,), "bn1.running_var": (48,),
    "b2.weight": (48, 48, 5), "b2.bias": (48,), "bn2.weight": (48,), "bn2.bias": (48,), "bn2.running_mean": (48,), "bn2.running_var": (48,),
    "b3.weight": (64, 48, 5), "b3.bias": (64,), "bn3.weight": (64,), "bn3.bias": (64,), "bn3.running_mean": (64,), "bn3.running_var": (64,),
    "b4.weight": (64, 64, 5), "b4.bias": (64,), "bn4.weight": (64,), "bn4.bias": (64,), "bn4.running_mean": (64,), "bn4.running_var": (64,),
    "fc1.weight": (64, 256), "fc1.bias": (64,), "fc2.weight": (1, 64), "fc2.bias": (1,),
}


def flatten(value, shape):
    if len(shape) == 1:
        if not isinstance(value, list) or len(value) != shape[0]:
            raise SystemExit("unexpected tensor shape")
        return [float(v) for v in value]
    if not isinstance(value, list) or len(value) != shape[0]:
        raise SystemExit("unexpected tensor shape")
    out = []
    for row in value:
        out += flatten(row, shape[1:])
    return out


def f32(x: float) -> float:
    return struct.unpack("<f", struct.pack("<f", x))[0]


def c_name(name: str) -> str:
    return "g2_" + name.replace(".", "_")


def weight_table_digest(tensors: dict) -> str:
    """SHA-256 of every tensor in SHAPES order as little-endian binary32 (the exact bytes the native evaluator consumes)."""
    h = hashlib.sha256()
    for name in SHAPES:
        for v in tensors[name]:
            h.update(struct.pack("<f", v))
    return h.hexdigest()


def render(model_bytes: bytes, frozen: dict) -> str:
    model_bytes = model_bytes.replace(b"\r\n", b"\n")  # a Windows checkout may translate line endings; the digest is of the LF form
    model_sha = hashlib.sha256(model_bytes).hexdigest()
    if model_sha != frozen["model_artifact"]["sha256"]:
        raise SystemExit("model artifact digest differs from the frozen record")
    model = json.loads(model_bytes)
    if model.get("schema") != "segarecomp.ml_region_gen2_model.v1" or model.get("model") != "M3" or model.get("trainable_parameters") != 77441:
        raise SystemExit("unexpected model identity")
    weights = model["weights"]
    if set(weights) != set(SHAPES):
        raise SystemExit("unexpected tensor set")
    tensors = {}
    for name, shape in SHAPES.items():
        flat = flatten(weights[name], shape)
        want = 1
        for d in shape:
            want *= d
        if len(flat) != want:
            raise SystemExit("unexpected tensor size")
        # The freeze exports each binary32 weight with 9 significant digits, which round-trips it exactly: rounding to binary32 recovers it.
        if any(f32(v) != f32(float("%.9g" % f32(v))) or v != v or abs(v) == float("inf") for v in flat):
            raise SystemExit(f"{name}: value is not a finite binary32 round trip")
        tensors[name] = [f32(v) for v in flat]
    policy = frozen["policy"]
    if policy["id"] != "B35" or policy["percent"] != 35:
        raise SystemExit("unexpected frozen policy")
    lines = [
        "// GENERATED by tools/segarecomp_ml_region_gen2_native_data.py from tools/segarecomp_ml_region_gen2.model.json. DO NOT EDIT.",
        "// SEG-049-T003 (ADR 0102). Generic learned parameters of the frozen gen2 M3 CNN only; binary32 shortest round-trip decimal literals.",
        f'inline constexpr const char *g2_source_model_sha256 = "{model_sha}";',
        f'inline constexpr const char *g2_representation_version = "{frozen["representation_version"]}";',
        f'inline constexpr const char *g2_representation_sha256 = "{frozen["representation_sha256"]}";',
        f'inline constexpr const char *g2_token_schema_sha256 = "{frozen["token_schema_sha256"]}";',
        f'inline constexpr const char *g2_rank_plan_sha256 = "{frozen["rank_plan_sha256"]}";',
        f'inline constexpr const char *g2_policy_id = "{policy["id"]}";',
        f"inline constexpr unsigned g2_policy_percent = {policy['percent']};",
        f'inline constexpr const char *g2_weight_table_sha256 = "{weight_table_digest(tensors)}";',
    ]
    for name, shape in SHAPES.items():
        flat = tensors[name]
        lines.append(f"inline constexpr float {c_name(name)}[{len(flat)}] = {{")
        for i in range(0, len(flat), 8):
            lines.append("    " + ", ".join(repr_f32(v) for v in flat[i:i + 8]) + ",")
        lines.append("};")
    lines.append("")
    return "\n".join(lines)


def repr_f32(v: float) -> str:
    """Shortest decimal that round-trips binary32 (at most 9 significant digits), with the `f` suffix."""
    for digits in range(1, 10):
        text = "%.*g" % (digits, v)
        if f32(float(text)) == v:
            break
    if "." not in text and "e" not in text and "inf" not in text and "nan" not in text:
        text += ".0"
    elif "e" in text and "." not in text.split("e")[0]:
        mant, exp = text.split("e")
        text = mant + ".0e" + exp
    return text + "f"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="fail when the checked-in table differs from the frozen model artifact")
    args = parser.parse_args()
    text = render(MODEL.read_bytes(), json.loads(FROZEN.read_text()))
    if args.check:
        if OUTPUT.read_text().replace("\r\n", "\n") != text:
            print("native gen2 model table drifted from tools/segarecomp_ml_region_gen2.model.json", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
