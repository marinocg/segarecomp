#!/usr/bin/env python3
"""Generates libs/viewer/src/sv_font_data.c: the in-game viewer's bitmap font atlas (offline, Pillow; the output is committed, nothing here runs at build time).

Two faces, both rendered 1-bit (pure pixel fonts, scaled by whole numbers at run time so they stay crisp at any display density):
  BODY  ProggyClean rendered at ppem 16 (its hinted 7-pixel-advance form, the 13 px "ImGui default" look; mixed case, readable, MIT) - the same family as the launcher's body text (Dear ImGui's embedded ProggyForever is its vector
        cousin);
  HEAD  Silkscreen Bold at its native 8 px (SIL OFL 1.1, apps/segarecomp-launcher/assets/fonts) - the heading face of the launcher and of the design boards.
Printable ASCII only (32..126); every other code point draws as '?'. The file embeds a 1-bit atlas, per-glyph metrics and the face metrics, so the viewer needs no font
file at run time and no font library (the packaged per-game C11 build gains one small translation unit).

usage: gen_viewer_font.py --proggy <ProggyClean.ttf> --silkscreen <Silkscreen-Bold.ttf> --out libs/viewer/src/sv_font_data.c
"""
import argparse
import hashlib
import pathlib

from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 32, 126
ATLAS_W = 256


def render_face(path, size, fontmode="1", nominal=None):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        cell = Image.new("L", (size * 3, size * 3), 0)
        draw = ImageDraw.Draw(cell)
        draw.fontmode = fontmode
        base_x, base_y = size, size * 2
        draw.text((base_x, base_y), ch, font=font, fill=255, anchor="ls")
        box = cell.getbbox()
        adv = int(round(font.getlength(ch)))
        if box is None:
            glyphs.append({"code": code, "img": None, "w": 0, "h": 0, "xoff": 0, "yoff": 0, "adv": max(adv, 1)})
            continue
        crop = cell.crop(box)
        glyphs.append({"code": code, "img": crop, "w": crop.width, "h": crop.height, "xoff": box[0] - base_x, "yoff": box[1] - base_y, "adv": max(adv, box[2] - base_x)})
    return {"ascent": ascent, "descent": descent, "glyphs": glyphs, "size": nominal or size}


def pack(faces):
    x = y = row_h = 0
    for face in faces:
        for g in face["glyphs"]:
            if g["img"] is None:
                g["x"] = g["y"] = 0
                continue
            if x + g["w"] + 1 > ATLAS_W:
                x, y, row_h = 0, y + row_h + 1, 0
            g["x"], g["y"] = x, y
            x += g["w"] + 1
            row_h = max(row_h, g["h"])
    height = y + row_h + 1
    height = (height + 7) // 8 * 8
    atlas = Image.new("L", (ATLAS_W, height), 0)
    for face in faces:
        for g in face["glyphs"]:
            if g["img"] is not None:
                atlas.paste(g["img"], (g["x"], g["y"]))
    return atlas


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--proggy", required=True)
    parser.add_argument("--silkscreen", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    faces = [render_face(args.proggy, 16, nominal=13), render_face(args.silkscreen, 8)]
    atlas = pack(faces)
    bits = bytearray()
    for y in range(atlas.height):
        for bx in range(0, ATLAS_W, 8):
            byte = 0
            for k in range(8):
                byte = (byte << 1) | (1 if atlas.getpixel((bx + k, y)) >= 128 else 0)
            bits.append(byte)
    lines = ["/* GENERATED by tools/gen_viewer_font.py - do not edit. Bitmap font atlas of the in-game viewer (SDL free).",
             " * BODY: ProggyClean (hinted at ppem 16, 7 px advance), Copyright (c) 2004, 2005 Tristan Grimmer, MIT license (http://www.proggyfonts.net/).",
             " * HEAD: Silkscreen Bold 8 px, Copyright The Silkscreen Project Authors, SIL Open Font License 1.1 (apps/segarecomp-launcher/assets/fonts/Silkscreen-OFL.txt).",
             " * atlas sha256 %s */" % hashlib.sha256(bytes(bits)).hexdigest(),
             '#include "sv_font.h"', "",
             "const int sv_font_atlas_w = %d;" % ATLAS_W, "const int sv_font_atlas_h = %d;" % atlas.height, "",
             "const unsigned char sv_font_atlas_bits[%d] = {" % len(bits)]
    for i in range(0, len(bits), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in bits[i:i + 24]) + ",")
    lines += ["};", "", "const SvFontFace sv_font_faces[SV_FONT_COUNT] = {"]
    for face in faces:
        lines.append("  {%d, %d, %d, {" % (face["size"], face["ascent"], face["descent"]))
        for g in face["glyphs"]:
            lines.append("    {%d, %d, %d, %d, %d, %d, %d}, /* %s */" % (g["x"], g["y"], g["w"], g["h"], g["xoff"], g["yoff"], g["adv"], repr(chr(g["code"]))[1:-1].replace("*/", "* /")))
        lines.append("  }},")
    lines.append("};")
    pathlib.Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("atlas %dx%d, %d bytes of bits; wrote %s" % (ATLAS_W, atlas.height, len(bits), args.out))


if __name__ == "__main__":
    main()
